import { test,expect } from '@playwright/test';
test('the complete love story, drawing, flowers, surprise and replay',async({page},testInfo)=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/demo');
 await expect(page.getByRole('heading',{name:/Hey You/})).toBeVisible();
 await expect(page.locator('.scene-content')).toHaveCSS('opacity','1');
 await page.screenshot({path:`test-results/${testInfo.project.name}-intro.png`,fullPage:true});
 await page.getByRole('button',{name:'Play music'}).click();
 await expect(page.getByRole('button',{name:'Mute music'})).toBeVisible();
 await page.getByRole('button',{name:'Mute music'}).click();
 await page.getByRole('button',{name:/Start the Love Test/}).click();
 const range=page.getByRole('slider');await expect(range).toHaveValue('0');
 await range.fill('20');await expect(range).toHaveValue('20');
 await expect(page.getByRole('status')).toContainText('A little? Are you sure?');
 await range.fill('100');await expect(page.getByRole('status')).toContainText('TO THE MOON & BACK!');
 await expect(page.locator('.scene-content')).toHaveCSS('opacity','1');
 await expect(page.getByTestId('meter-needle')).toHaveAttribute('data-angle','90');
 await page.screenshot({path:`test-results/${testInfo.project.name}-meter.png`,fullPage:true});
 await page.getByRole('button',{name:'Continue →',exact:true}).click();
 await page.getByRole('button',{name:'More than you know'}).click();await expect(page.getByRole('status')).toContainText('my heart was hoping');
 for(const name of ['Every little second ♡','Me, obviously ♡','A thousand times, yes','My absolute favorite ♡']) await page.getByRole('button',{name,exact:true}).click();
 const canvas=page.locator('canvas');await expect(canvas).toBeVisible();
 await expect(page.getByRole('button',{name:'Done ♡',exact:true})).toBeDisabled();
 const box=(await canvas.boundingBox())!;
 if(testInfo.project.name==='desktop'){
 await page.mouse.move(box.x+box.width*.5,box.y+box.height*.7);await page.mouse.down();
 for(const [x,y] of [[.2,.4],[.25,.2],[.4,.2],[.5,.35],[.6,.2],[.75,.2],[.8,.4],[.5,.7]])await page.mouse.move(box.x+box.width*x,box.y+box.height*y,{steps:4});await page.mouse.up();
 }else{
 const session=await page.context().newCDPSession(page);
 await session.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:box.x+50,y:box.y+50}]});
 await session.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:box.x+100,y:box.y+100}]});
 await session.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
 }
 await expect(page.getByRole('button',{name:'Done ♡',exact:true})).toBeEnabled();
 await page.getByRole('button',{name:'Clear',exact:true}).click();await expect(page.getByRole('button',{name:'Done ♡',exact:true})).toBeDisabled();
 if(testInfo.project.name==='mobile')await canvas.tap({position:{x:80,y:80}});
 else await canvas.click({position:{x:80,y:80}});
 await page.getByRole('button',{name:'Done ♡',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('Masterpiece');
 await page.getByRole('button',{name:'Keep this in my heart →'}).click();
 await expect(page.getByRole('button',{name:'For you, with love →'})).toBeDisabled();
 const choices=page.locator('.flower-options button');
 for(let i=0;i<6;i++)await choices.nth(i).click();
 await expect(page.locator('.bouquet')).toHaveAttribute('aria-label','Bouquet with 7 flowers');
 await choices.first().click();await expect(choices.first()).toHaveAttribute('aria-pressed','false');await choices.first().click();
 await expect(page.locator('.scene-content')).toHaveCSS('opacity','1');
 await page.screenshot({path:`test-results/${testInfo.project.name}-bouquet.png`,fullPage:true});
 await page.getByRole('button',{name:'For you, with love →'}).click();
 await page.getByRole('button',{name:'Open your surprise 🎁'}).click();
 await expect(page.locator('.gift-particle')).toHaveCount(14);
 await expect(page.getByRole('heading',{name:'A Letter From My Heart'})).toBeVisible();
 await expect(page.locator('.scene-content')).toHaveCSS('opacity','1');
 await page.screenshot({path:`test-results/${testInfo.project.name}-letter.png`,fullPage:true});
 await page.getByRole('button',{name:'One more little thing →'}).click();
 await expect(page.getByRole('heading',{name:'I LOVE YOU ❤️'})).toBeVisible();
 await expect(page.locator('body')).toHaveJSProperty('scrollWidth',await page.evaluate(()=>window.innerWidth));
 await page.getByRole('button',{name:'Replay our love test ↻'}).click();
 await expect(page.getByRole('heading',{name:/Hey You/})).toBeVisible();
 await page.getByRole('button',{name:/Start the Love Test/}).click();await expect(page.getByRole('slider')).toHaveValue('0');
 expect(errors).toEqual([]);
});
